import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const posts = JSON.parse(await readFile(new URL('../src/data/defaultPosts.json', import.meta.url), 'utf8'));
const current = posts.find(post => post.id === 'default-it-books-current');
const planned = posts.find(post => post.id === 'default-it-books-planned');
const mixedCurrent = posts.find(post => post.id === 'default-mixed-books-current');
const mixedPlanned = posts.find(post => post.id === 'default-mixed-books-planned');
const gamesCurrent = posts.find(post => post.id === 'default-switch-games-current');
const gamesPlanned = posts.find(post => post.id === 'default-switch-games-planned');

assert.equal(current?.format, 'current');
assert.equal(planned?.format, 'planned');
assert.equal(current?.title, 'IT기술서, 자기계발서 등 30권');
assert.equal(planned?.title, current.title);
assert.equal(current?.items.length, 1);
assert.equal(current?.items[0].price, 2700);
assert.equal(planned?.items.length, 30);
assert.equal(planned.items.filter(item => item.soldOut).length, 3);
assert.equal(planned.items.find(item => item.name === '조국의 시간')?.price, 0);
assert.equal(current?.directBuy, true);
assert.equal(planned?.directBuy, true);
assert.equal(current?.photos.length, 3);
assert.equal(planned?.photos.length, 3);
assert.equal(mixedCurrent?.format, 'current');
assert.equal(mixedPlanned?.format, 'planned');
assert.equal(mixedCurrent?.title, '다양한 분야의 중고 도서 묶음');
assert.equal(mixedPlanned?.title, mixedCurrent.title);
assert.equal(mixedCurrent?.items.length, 1);
assert.equal(mixedPlanned?.items.length, 71);
assert.ok(mixedPlanned?.items.every(item => item.price === 2000 && item.quantity === 1));
assert.equal(mixedCurrent?.directBuy, true);
assert.equal(mixedPlanned?.directBuy, true);
assert.equal(mixedCurrent?.photos.length, 2);
assert.equal(mixedPlanned?.photos.length, 2);
assert.equal(gamesCurrent?.format, 'current');
assert.equal(gamesPlanned?.format, 'planned');
assert.equal(gamesCurrent?.title, '닌텐도 스위치 게임 타이틀 다수');
assert.equal(gamesPlanned?.title, gamesCurrent.title);
assert.equal(gamesCurrent?.items.length, 1);
assert.equal(gamesCurrent?.items[0].price, 13000);
assert.equal(gamesPlanned?.items.length, 33);
assert.equal(gamesPlanned?.items.filter(item => item.soldOut).length, 1);
assert.equal(gamesPlanned?.items.find(item => item.name === '진 여신전쟁5')?.price, 13000);
assert.equal(gamesCurrent?.directBuy, true);
assert.equal(gamesPlanned?.directBuy, true);
assert.equal(gamesCurrent?.photos.length, 1);
assert.equal(gamesPlanned?.photos.length, 1);
console.log('default book posts: ok');
